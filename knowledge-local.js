/**
 * 搜索知识库
 * @param {string} query - 用户查询关键词
 * @returns {Promise<Array>} 匹配的故障记录列表
 */
async function knowledgeSearch(query) {
    console.log(`[知识库搜索] 关键词: "${query}"`);

    // 智能分词：将查询分解成更小的关键词
    let keywords = query.toLowerCase().split(/\s+/).filter(k => k.length > 1);

    // 如果只有一个关键词且长度>2，尝试进一步分割（针对没有空格的查询）
    if (keywords.length === 1 && keywords[0].length > 2) {
        // 常见IVD术语字典
        const ivdTerms = ['加样臂', '加样针', '抓手', '泵盒', '试剂仓', '盖玻片', '样本轨道', '干涉', '漏液', '歪斜', '不良', '故障'];
        
        // 尝试匹配IVD术语
        const extraTerms = [];
        ivdTerms.forEach(term => {
            if (keywords[0].includes(term.toLowerCase())) {
                extraTerms.push(term.toLowerCase());
            }
        });
        
        // 如果找到了额外的IVD术语，添加它们
        if (extraTerms.length > 0) {
            keywords = [...keywords, ...extraTerms];
        }
    }

    // 去重
    keywords = [...new Set(keywords)];

    if (keywords.length === 0) {
        return [];
    }

    console.log(`[分词结果] 关键词: ${keywords.join(', ')}`);

    // 匹配逻辑：只要任意一个关键词匹配即可
    const matched = knowledgeData.filter(record => {
        const searchText = (
            record.异常描述 +
            record.异常分类 +
            record.模块 +
            record.根本原因 +
            record.临时措施 +
            record.永久措施
        ).toLowerCase();

        // 检查是否包含任意关键词（使用OR逻辑）
        return keywords.some(keyword => searchText.includes(keyword));
    });

    console.log(`[搜索结果] 找到 ${matched.length} 条记录`);

    return matched;
}

